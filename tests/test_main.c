int main(int argc, char **argv) {
    tb_mem_init(TB_DEFAULT_HEAP_LIMIT);
    printf("=== TB Verification & Sub-10MB Memory Stress Suite ===\n");

    size_t n_suites = sizeof(TEST_SUITES) / sizeof(TEST_SUITES[0]);
    if (argc <= 1) {
        for (size_t i = 0; i < n_suites; i++) {
            TEST_SUITES[i].fn();
        }
    } else {
        size_t ran = 0;
        for (size_t i = 0; i < n_suites; i++) {
            bool match = false;
            for (int a = 1; a < argc; a++) {
                if (strcmp(argv[a], TEST_SUITES[i].name) == 0 ||
                    strcmp(argv[a], TEST_SUITES[i].group) == 0) {
                    match = true;
                    break;
                }
            }
            if (match) {
                TEST_SUITES[i].fn();
                ran++;
            }
        }
        if (ran == 0) {
            fprintf(stderr, "Unknown test filter. Available groups: core, engine, js, net, tls\n");
            return 1;
        }
    }

    printf("======================================================\n");
    printf("Result: %d assertions passed, %d failed.\n", g_pass, g_fail);
    return (g_fail == 0) ? 0 : 1;
}
